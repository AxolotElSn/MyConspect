// rest оператор и значения по умолчанию

'use strict';

const log = function(a, b, ...rest) { // ... - rest оператор. Значит что после обязательный аргументов, может еще быть сколько угодно аргументов. Тоесть ту a и b - обязательные аргументы которые должны быть в ф-ии, но после них еще может быть сколько угодно
    console.log(a, b, rest); // важно, что все что в rest Операторе, выведется в массиве
}

log('basic', 'rest', 'operator', 'usage'); // basic rest [ 'operator', 'usage' ]


function calcOrDouble(number, basis = 2) { // = 2 в аргументе - значение по умолчанию. ВЫ случае если аргумент не будет передан, то подставится значение по умолчанию
    console.log(number * basis);
}

calcOrDouble(3);


