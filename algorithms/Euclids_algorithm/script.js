// Алгоритм Евклида
// Алгоритм Евклида — это метод нахождения наибольшего общего делителя двух целых чисел. Назван в честь древнегреческого математика Евклида, описан в его труде «Начала» (около 300 г. до н. э.) — это один из древнейших известных алгоритмов, доживших до наших дней.

// Суть алгоритма
// НОД(a, b) — наибольшее число, которое делит и a, и b без остатка.

// Ключевая идея — свойство остатка:

// НОД(a, b) = НОД(b, a % b)
// То есть наибольший общий делитель пары (a, b) равен наибольшему общему делителю пары (b, остаток от деления a на b).


'use strict';

function gcd(a, b) {
    if (b === 0) {
        return a;
    }
    return gcd(b, a % b);
}

console.log(gcd(48, 18));   // 6
console.log(gcd(17, 5));    // 1
console.log(gcd(100, 0));   // 100