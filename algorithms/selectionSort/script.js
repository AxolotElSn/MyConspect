// Сортировка выбором (selection sort) — алгоритм, который строит отсортированный результат так: Находит минимальный элемент в неотсортированной части. Ставит его в конец уже отсортированной части (или извлекает из массива). Повторяет, пока не останется элементов.

// Ключевая идея: на каждом шаге мы точно знаем, что нашли самый маленький из оставшихся — поэтому его место в результате окончательное и больше мы к нему не вернёмся.

// Сложность:
// Время — O(n²): на каждом из n шагов просматриваем ~n оставшихся элементов.
// Память — зависит от реализации: in-place O(1) или с новым массивом O(n).

// Плюсы и минусы этой реализации
// Плюсы:
// Простая и наглядная.
// Всегда O(n²) — предсказуемо (в отличие от quicksort, у которого худший случай O(n²), а средний O(n log n)).

// Минусы:
// O(n²) — медленно для больших массивов (для 10 000 элементов — ~50 млн операций).
// Мутирует исходный массив — splice опустошает arr. Если нужно сохранить оригинал: let arr = [...original] в начале.
// O(n) дополнительной памяти — из-за newArr. Классическая in-place версия (через swap) использует O(1).
// Неустойчивая в in-place варианте — равные элементы могут поменяться местами.

// in place - Алгоритм переставляет элементы внутри того же массива, а не строит новый. Входной массив после работы становится отсортированным (или как-то изменённым) — и это и есть результат.

'use strict';

function findSmallest(arr) {
    let smallest = arr[0]; // Берём первый элемент как временно минимальный. Это стартовое значение для сравнения.
    let smallestIndex = 0; // Запоминаем индекс этого минимального значения

    for (let i = 1; i < arr.length; i++) { // Проходим по массиву, начиная с индекса 1 (индекс 0 уже учтён как стартовый минимум). Сравнивать arr[0] с самим собой нет смысла.
        if (arr[i] < smallest) { // Если текущий элемент меньше текущего минимума — нашли нового «кандидата» на минимум
            smallest = arr[i]; // Обновляем значение минимума
            smallestIndex = i; // Обновляем индекс минимума
        }
    }

    return smallestIndex; // Возвращаем индекс наименьшего элемента
}


function selectionSort(arr) {
    let newArr = []; // Создаём пустой массив, куда будем складывать элементы по возрастанию

    while (arr.length > 0) { // Крутимся, пока в исходном массиве есть элементы
        let smallest = findSmallest(arr); // Находим индекс минимального элемента в текущем (ещё не отсортированном) массиве.
        newArr.push(arr.splice(smallest, 1)[0]); // 1 шаг. Это переменная — индекс минимального элемента, который вернула findSmallest(arr) строкой выше. 2 шаг. arr.splice(smallest, 1) - изменяет массив на месте и возвращает МАССИВ удалённых элементов. 3 шаг. [0] splice вернул [-2] — массив из одного элемента. Берём [0] — получаем само значение -2. Теперь у нас есть готовое значение, которое нужно положить в результат. Шаг 4 newArr.push(...) добавляем элемент в конец нового массива
    }

    return newArr;
}

console.log(selectionSort([3, -1, 20, -2, 5]));  // [-2, -1, 3, 5, 20]